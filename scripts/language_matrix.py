#!/usr/bin/env python3
"""Print (or write) the language availability matrix computed from the real database.

    python scripts/language_matrix.py                       # markdown to stdout
    python scripts/language_matrix.py --out docs/LANGUAGE_AVAILABILITY_MATRIX.md
"""
from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.app import languages  # noqa: E402
from backend.app.config import load_settings  # noqa: E402
from backend.app.db import get_db  # noqa: E402


def render() -> str:
    settings = load_settings()
    with get_db(settings.db_path) as conn:
        items = languages.describe(conn, settings.web_dir / "locales")
    lines = [
        "# Language Availability Matrix",
        "",
        f"Generated by `scripts/language_matrix.py` on {datetime.now(timezone.utc):%Y-%m-%d} (UTC) from the "
        "database and `web/locales/`. Do not edit by hand.",
        "",
        "| # | Language | Native name | Code | BCP 47 | Script | Dir | Interface | Labels | Interface text by | Confidence | Owner summaries | Official text (articles) | OCR awaiting review | Machine-translated law | Human-verified | Assistant answers in language | Statuses |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for n, i in enumerate(items, 1):
        ui, c = i["ui"], i["content"]
        ui_state = "ready" if "UI_READY" in i["statuses"] else ("partial" if "UI_PARTIAL" in i["statuses"] else "none")
        lines.append(
            f"| {n} | {i['english_name']} | {i['native_name']} | `{i['code']}` | `{i['tag']}` | {i['script']} | {i['direction']} | "
            f"{ui_state} | {ui['keys']}/{ui['reference_keys']} | {ui['translation_status']} | {ui['confidence'] or '—'} | "
            f"{c['owner_summaries']} | {c['official_text_articles']} | {c['ocr_review_required_articles']} | "
            f"{c['machine_translated_articles']} | {c['human_verified_articles']} | "
            f"{'yes' if i['assistant']['answers_in_language'] else 'no — answers in ' + i['assistant']['answer_language']} | "
            f"{', '.join(i['statuses']) or '—'} |"
        )
    ready = sum(1 for i in items if "UI_READY" in i["statuses"])
    lines += [
        "",
        f"**Totals:** {len(items)} languages · interface ready {ready} · interface partial "
        f"{sum(1 for i in items if 'UI_PARTIAL' in i['statuses'])} · with owner summaries "
        f"{sum(1 for i in items if i['content']['owner_summaries'])} · with official text "
        f"{sum(1 for i in items if i['content']['official_text_articles'])} · human-verified "
        f"{sum(1 for i in items if i['content']['human_verified_articles'])} · assistant answers in language "
        f"{sum(1 for i in items if i['assistant']['answers_in_language'])}.",
        "",
        "## How to read it",
        "",
        "* **Interface ready** = all ten essential labels (navigation, search, language) exist in that language. "
        "It says nothing about quality: see *Interface text by* and *Confidence*.",
        "* **MACHINE_TRANSLATED** interface text was generated by an AI model and has **not** been reviewed by a "
        "native speaker. The app shows a notice in every such language. *low* confidence means labels the model "
        "was unsure of were left in English instead of being guessed.",
        "* **PROJECT_AUTHORED** = written for this project in its two working languages; not independently reviewed.",
        "* **Owner summaries** are explanations written by the project owner. They are not the text of the law.",
        "* **Official text**, **OCR awaiting review**, **Machine-translated law** and **Human-verified** count rows "
        "of `article_texts`. Machine-translated law is 0 by design: the project does not machine-translate the Constitution.",
        "* For a language without content the app shows the English (or Gujarati) content and says so; the "
        "assistant accepts the question, recognises the script and article number, and answers in English with a notice.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--out" in sys.argv:
        Path(sys.argv[sys.argv.index("--out") + 1]).write_text(text, encoding="utf-8")
    else:
        print(text)
